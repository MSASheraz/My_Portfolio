  <script>
    document.addEventListener("DOMContentLoaded", () => {
      gsap.registerPlugin(ScrollTrigger);

      const header = document.querySelector(".gsap-fade-in");
      const leftCard = document.querySelector(".gsap-left-card");
      const rightCard = document.querySelector(".gsap-right-card");
      
      // Select all designated interior text node configurations
      const textNodes = gsap.utils.toArray(".gsap-text-node");

      // Set hardware parameters safely
      [header, leftCard, rightCard].forEach(el => {
        if(el) {
          el.classList.add("gsap-engine-active");
          el.style.willChange = "transform, opacity";
        }
      });
      textNodes.forEach(text => {
        text.style.willChange = "transform, opacity";
      });

      // Explicit layout initial position parameters
      gsap.set(header, { y: -15, opacity: 0 });
      gsap.set(leftCard, { x: -30, opacity: 0 });
      gsap.set(rightCard, { x: 30, opacity: 0 });
      gsap.set(textNodes, { y: 15, opacity: 0 });

      // Unified Matrix Master Timeline that runs immediately on load
      const showPageTimeline = gsap.timeline();

      // Step 1: Nav panel enters header area
      showPageTimeline.to(header, {
        y: 0,
        opacity: 1,
        duration: 0.55,
        ease: "power3.out"
      });

      // Step 2: Left Content Box & Right Sidebar containers enter simultaneously
      showPageTimeline.to(leftCard, {
        x: 0,
        opacity: 1,
        duration: 0.75,
        ease: "power4.out"
      }, "-=0.3");

      showPageTimeline.to(rightCard, {
        x: 0,
        opacity: 1,
        duration: 0.75,
        ease: "power4.out"
      }, "-=0.75");

      // Step 3: All text sub-elements inside containers stagger seamlessly
      showPageTimeline.to(textNodes, {
        y: 0,
        opacity: 1,
        stagger: 0.08,             // 0.08s smooth gap between each text block element
        duration: 0.65,
        ease: "power3.out",
        onComplete: () => {
          // Release elements smoothly from active animation layer logic
          [header, leftCard, rightCard].forEach(el => {
            if(el) {
              el.classList.remove("gsap-engine-active");
              el.style.willChange = "auto";
            }
          });
          textNodes.forEach(text => text.style.willChange = "auto");
        }
      }, "-=0.4"); // Starts loading text elements slightly before container finish
    });
  </script>
